'use strict';

const fs = require('node:fs');
const path = require('node:path');

const repositoryRoot = path.resolve(__dirname, '..');
const schemaPath = path.join(repositoryRoot, 'docs/contracts/noor-rag-v1.schema.json');
const outputPaths = [
    path.join(repositoryRoot, 'functions/src/noor-rag/generatedContract.ts'),
    path.join(repositoryRoot, 'src/features/noor-ai/domain/generatedContract.ts'),
];

function referenceName(reference) {
    const prefix = '#/$defs/';
    if (typeof reference !== 'string' || !reference.startsWith(prefix)) {
        throw new Error(`Unsupported schema reference: ${String(reference)}`);
    }
    return reference.slice(prefix.length);
}

function renderLiteral(value) {
    if (typeof value !== 'string' && typeof value !== 'number' && typeof value !== 'boolean') {
        throw new Error('Contract literals must be strings, numbers, or booleans');
    }
    return JSON.stringify(value);
}

function renderType(definition) {
    if (definition.$ref !== undefined) {
        return referenceName(definition.$ref);
    }
    if (definition.const !== undefined) {
        return renderLiteral(definition.const);
    }
    if (Array.isArray(definition.enum)) {
        return definition.enum.map(renderLiteral).join(' | ');
    }
    if (Array.isArray(definition.oneOf)) {
        return definition.oneOf.map(renderType).join(' | ');
    }
    if (definition.not !== undefined && Object.keys(definition.not).length === 0) {
        return 'never';
    }
    if (definition.type === 'array') {
        return `Array<${renderType(definition.items)}>`;
    }
    if (definition.type === 'string') {
        return 'string';
    }
    if (definition.type === 'integer' || definition.type === 'number') {
        return 'number';
    }
    if (definition.type === 'boolean') {
        return 'boolean';
    }
    throw new Error(`Unsupported schema definition: ${JSON.stringify(definition)}`);
}

function renderDefinition(name, definition) {
    if (definition.type !== 'object') {
        return `export type ${name} = ${renderType(definition)};`;
    }

    const required = new Set(definition.required || []);
    const properties = definition.properties || {};
    const fields = Object.entries(properties).map(([propertyName, propertyDefinition]) => {
        const optional = required.has(propertyName) ? '' : '?';
        return `    ${propertyName}${optional}: ${renderType(propertyDefinition)};`;
    });
    return [`export interface ${name} {`, ...fields, '}'].join('\n');
}

function generateContract(schema) {
    if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema') {
        throw new Error('Noor contract must use JSON Schema draft 2020-12');
    }
    if (schema.$defs === undefined || typeof schema.$defs !== 'object') {
        throw new Error('Noor contract schema is missing $defs');
    }

    const publicDefinitions = [
        'NoorSource',
        'NoorHistoryRole',
        'RequestId',
        'Question',
        'QuranSurah',
        'QuranVerse',
        'NoorHistoryTurn',
        'NoorVerseContext',
        'NoorChatRequest',
        'NoorVerseSummaryRequest',
        'NoorVerseQuestionRequest',
        'NoorRequest',
        'NoorStatus',
        'NoorCitation',
        'NoorQuotaExceededAnswer',
        'NoorNonQuotaAnswer',
        'NoorAnswer',
    ];
    const rendered = publicDefinitions.map((name) => {
        const definition = schema.$defs[name];
        if (definition === undefined) {
            throw new Error(`Noor contract schema is missing ${name}`);
        }
        return renderDefinition(name, definition);
    });

    return [
        '// Generated by scripts/generate-noor-contract.js from docs/contracts/noor-rag-v1.schema.json.',
        '// Do not edit this file directly.',
        '',
        ...rendered.flatMap((definition) => [definition, '']),
    ].join('\n');
}

function main() {
    const argumentsList = process.argv.slice(2);
    const checkOnly = argumentsList.includes('--check');
    const unexpectedArguments = argumentsList.filter((argument) => argument !== '--check');
    if (unexpectedArguments.length > 0) {
        throw new Error(`Unexpected arguments: ${unexpectedArguments.join(', ')}`);
    }

    const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
    const generated = generateContract(schema);
    const driftedPaths = outputPaths.filter((outputPath) => {
        return !fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated;
    });

    if (checkOnly) {
        if (driftedPaths.length > 0) {
            process.stderr.write(`Noor generated contract drift: ${driftedPaths.join(', ')}\n`);
            process.exitCode = 1;
        }
        return;
    }

    for (const outputPath of driftedPaths) {
        fs.mkdirSync(path.dirname(outputPath), { recursive: true });
        fs.writeFileSync(outputPath, generated, 'utf8');
    }
}

main();
