import React, { createContext, useContext, useState, useEffect, useCallback, useMemo } from 'react';
import { Alert } from 'react-native';
import { useRouter } from 'expo-router';
import { usePro } from '../../auth/infrastructure/ProContext';
import { Note } from '../domain/Note';
import { LocalNoteRepository } from '../data/LocalNoteRepository';
import {
    SaveNoteUseCase,
    GetNoteUseCase,
    GetAllNotesUseCase,
    DeleteNoteUseCase,
    GetNoteByIdUseCase,
} from '../domain/usecases/NoteUseCases';
import { useStreaks } from '../../auth/infrastructure/StreakContext';
import { useAuth } from '../../auth/infrastructure/AuthContext';

interface NoteContextType {
    notes: Note[];
    loading: boolean;
    saveNote: (note: Note) => Promise<void>;
    deleteNote: (id: string) => Promise<void>;
    togglePin: (id: string) => Promise<void>;
    getNoteForVerse: (surah: number, verse: number) => Promise<Note | null>;
    getNoteById: (id: string) => Promise<Note | null>;
    refreshNotes: () => Promise<void>;
}

const NoteContext = createContext<NoteContextType | undefined>(undefined);

export const useNoteContext = () => {
    const context = useContext(NoteContext);
    if (!context) throw new Error('useNoteContext must be used within a NoteProvider');
    return context;
};

export function NoteProvider({ children }: { children: React.ReactNode }) {
    const [notes, setNotes] = useState<Note[]>([]);
    const [loading, setLoading] = useState(true);
    const { recordActivity } = useStreaks();
    const { isPro } = usePro();
    const { user } = useAuth();
    const userId = user?.id ?? null;
    const router = useRouter();
    const useCases = useMemo(() => {
        const repo = new LocalNoteRepository(userId);
        return {
            save: new SaveNoteUseCase(repo),
            get: new GetNoteUseCase(repo),
            getAll: new GetAllNotesUseCase(repo),
            delete: new DeleteNoteUseCase(repo),
            getById: new GetNoteByIdUseCase(repo),
        };
    }, [userId]);

    const refreshNotes = useCallback(async () => {
        setLoading(true);
        const data = await useCases.getAll.execute();
        setNotes(data);
        setLoading(false);
    }, [useCases]);

    useEffect(() => {
        refreshNotes();
    }, [refreshNotes]);

    const saveNote = async (note: Note) => {
        // GATING LOGIC: Limit Free users to 10 notes
        // Check if it's a NEW note (id might be generated by caller, but we can check if it already exists in state)
        // If note.id is already in notes, it's an update, which is allowed.
        // If it's new, we check limit.
        const isUpdate = notes.some(n => n.id === note.id);

        if (!isPro && !isUpdate && notes.length >= 7) {
            Alert.alert(
                'Note Limit Reached',
                'Free users can create up to 7 notes. Upgrade to Pro for unlimited notes.',
                [
                    { text: 'Cancel', style: 'cancel' },
                    { text: 'Upgrade to Pro', onPress: () => router.push('/paywall?reason=notes') }
                ]
            );
            return;
        }

        await useCases.save.execute(note);
        await recordActivity(); // Update streak
        await refreshNotes();
    };

    const deleteNote = async (id: string) => {
        await useCases.delete.execute(id);
        await refreshNotes();
    };

    const getNoteForVerse = async (surah: number, verse: number) => {
        return await useCases.get.execute(surah, verse);
    };

    const getNoteById = async (id: string) => {
        return await useCases.getById.execute(id);
    };

    const togglePin = async (id: string) => {
        const note = notes.find(n => n.id === id);
        if (!note) return;
        const updated = { ...note, isPinned: !note.isPinned, updatedAt: new Date() };
        await useCases.save.execute(updated);
        await refreshNotes();
    };

    return (
        <NoteContext.Provider
            value={{
                notes,
                loading,
                saveNote,
                deleteNote,
                togglePin,
                getNoteForVerse,
                getNoteById,
                refreshNotes,
            }}>
            {children}
        </NoteContext.Provider>
    );
}
